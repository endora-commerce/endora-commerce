/**
 * `endora generate` and an instance's overlay admin layers
 * (`specs/190-overlay-full-modules/` T043, T046; FR-080 – FR-082, FR-085;
 * `contracts/overlay-cli.md` §4).
 *
 * It renders one deployment admin registry per deployment under `apps/`, plus
 * bare core's, uncommitted; names each overlay admin layer in the stylesheet
 * enumeration; and judges palette coverage per deployment — writing everything
 * first and exiting 1 after, as the divergence report does.
 */
import { existsSync, readFileSync } from 'node:fs';
import { join } from 'node:path';

import { afterEach, describe, expect, it } from 'vitest';

import {
  generatePaletteRefusal,
  generateReport,
  GenerateInputError,
  runGenerate,
} from '../src/generate/index.js';
import { cleanInstances, instance, installModule, write, SCOPE } from './support/overlay-instance.js';

afterEach(() => {
  cleanInstances();
});

const LAYER = `import type { AdminContributions } from '${SCOPE}/admin-kit/contributions';

export const contributions: AdminContributions = {
  routes: [{ path: '/acme-board', component: () => import('./pages/Board.js'), index: true }],
};
`;

function manifest(id: string, actions: boolean): string {
  return (
    `export const manifest = {\n  id: '${id}',\n` +
    (actions ? `  actions: [{ id: 'open-${id}', targetRoute: '/acme-board' }],\n` : '') +
    `};\n`
  );
}

/** An instance with an admin member and one overlay module with an admin layer. */
function withAdmin(options: { actions?: boolean } = {}): string {
  const root = instance({ deployments: ['acme', 'beta'] });
  write(join(root, 'pnpm-workspace.yaml'), 'packages:\n  - backend\n  - admin\n');
  write(join(root, 'admin', 'package.json'), JSON.stringify({ name: 'acme-shop-admin' }));
  write(
    join(root, 'admin', 'tsconfig.json'),
    JSON.stringify({ compilerOptions: { baseUrl: '.', paths: { '@/*': ['./src/*'] } } }),
  );
  const board = join(root, 'apps', 'acme', 'modules', 'acme_board');
  write(join(board, 'manifest.ts'), manifest('acme_board', options.actions ?? true));
  write(join(board, 'admin', 'index.tsx'), LAYER);
  return root;
}

describe('endora generate — deployment admin registries', () => {
  it('renders none and one registry per deployment, each holding only its own layers', async () => {
    const root = withAdmin();
    const result = await runGenerate({ cwd: root });

    const deployments = join(root, 'admin', 'src', 'deployments');
    expect(readFileSync(join(deployments, 'none.generated.ts'), 'utf8')).not.toContain('/apps/');
    expect(readFileSync(join(deployments, 'beta.generated.ts'), 'utf8')).not.toContain('/apps/');
    const acme = readFileSync(join(deployments, 'acme.generated.ts'), 'utf8');
    expect(acme).toContain("from '../../../apps/acme/modules/acme_board/admin/index.js'");
    // The instance's header: never commit, regenerate with `pnpm run generate`.
    expect(acme).toMatch(/^\/\/ AUTO-GENERATED by `endora generate`/);
    expect(generateReport(result)).toContain(
      'wrote admin/src/deployments/acme.generated.ts — the admin registry of the deployment acme (1 overlay module(s))',
    );
  });

  it("names each overlay admin layer in the stylesheet enumeration", async () => {
    const root = withAdmin();
    await runGenerate({ cwd: root });
    expect(readFileSync(join(root, 'admin', 'src', 'tailwind.generated.css'), 'utf8')).toContain(
      '@source "../../apps/acme/modules/acme_board/admin";',
    );
  });

  it('refuses an admin layer under the wrong file name, writing nothing', async () => {
    const root = withAdmin();
    write(join(root, 'apps', 'beta', 'modules', 'beta_board', 'admin', 'index.ts'), 'export {};\n');
    await expect(runGenerate({ cwd: root })).rejects.toThrow(GenerateInputError);
    expect(existsSync(join(root, 'admin', 'src', 'deployments'))).toBe(false);
  });
});

describe('endora generate — palette coverage per deployment (FR-085)', () => {
  it('is clean when the overlay landing route has an action', async () => {
    const result = await runGenerate({ cwd: withAdmin() });
    expect(generatePaletteRefusal(result)).toBeNull();
    expect(generateReport(result)).toContain('palette coverage of acme: 1 overlay admin layer(s), clean');
  });

  it('writes the artefacts and then refuses a landing route with no action', async () => {
    const root = withAdmin({ actions: false });
    const result = await runGenerate({ cwd: root });

    expect(existsSync(join(root, 'admin', 'src', 'deployments', 'acme.generated.ts'))).toBe(true);
    const refusal = generatePaletteRefusal(result);
    expect(refusal).toContain('acme_board: landing route /acme-board has no palette action');
    expect(refusal).toContain('apps/acme/modules/acme_board/manifest.ts');
  });

  it("counts an installed package's action as covering the route", async () => {
    const root = withAdmin({ actions: false });
    installModule(root, 'catalog');
    write(
      join(root, 'node_modules', SCOPE, 'mod-catalog', 'dist', 'manifest.js'),
      "export const manifest = { id: 'catalog', actions: [{ id: 'board', targetRoute: '/acme-board' }] };\n",
    );
    const refusal = generatePaletteRefusal(await runGenerate({ cwd: root }));
    expect(refusal).not.toContain('landing route');
    expect(refusal).toContain('declares no palette action of its own');
  });
});
